from pathlib import Path

from tests.conftest import RunPristine


def test_unreadable_file_is_unchecked(run_pristine: RunPristine, tmp_path: Path) -> None:
    locked = tmp_path / "locked.py"
    locked.write_text("value = 1\n")
    locked.chmod(0)
    _, report = run_pristine({})
    locked.chmod(0o644)
    assert report["unchecked"] == [{"path": "locked.py", "reason": "could not read the file: Permission denied"}]


def test_reports_unchecked_and_skipped_files(run_pristine: RunPristine) -> None:
    _, report = run_pristine(
        {
            "notes.md": "# Notes\n",
            "uv.lock": "version = 1\n",
            "schema.py": "# @generated by protoc\nvalue = 1\n",
            "script.unknownlang": "run\n",
            "queries.ts": "// generated with @7nohe/openapi-react-query-codegen\nexport const value = 1;\n",
            "report.py": "value = 1\n# report generated by the nightly job\n",
        }
    )
    assert report["unchecked"] == [{"path": "script.unknownlang", "reason": "no grammar for this file type"}]
    assert [entry["path"] for entry in report["skipped"]] == ["notes.md", "queries.ts", "schema.py", "uv.lock"]
    assert [finding["path"] for finding in report["findings"]] == ["report.py"]


def test_markers_count_within_the_first_fifteen_lines_outside_quotes(run_pristine: RunPristine) -> None:
    openapi_header = (
        '# coding: utf-8\n\n"""\n    Billing API\n\n    The version of the OpenAPI document: 1.0\n'
        "    Generated by OpenAPI Generator (https://openapi-generator.tech)\n\n    Do not edit the class manually.\n"
    )
    _, report = run_pristine(
        {
            "client.py": f'{openapi_header}"""\n\nvalue = 1\n',
            "late.py": "value = 1\n" * 15 + "# @generated by protoc\n",
            "markers.py": 'MARKERS = ("@generated", "do not edit")\n',
        }
    )
    assert [entry["path"] for entry in report["skipped"]] == ["client.py"]


def test_binary_and_fixture_data_files_are_skipped(run_pristine: RunPristine) -> None:
    _, report = run_pristine(
        {
            "report.pdf": "%PDF-1.7\n%µ¶\n1 0 obj\n<< /Type /Catalog >>\nendobj\n",
            "fixtures/accounts.DAT": "0001 ALICE 100\n",
            "fixtures/total.in": "1 2\n",
            "fixtures/total.out": "3\n",
            "fixtures/render.golden": "<p>3</p>\n",
            "template/gitignore": "dist/\n",
            "build.recipe": "run\n",
        }
    )
    assert report["unchecked"] == [{"path": "build.recipe", "reason": "no grammar for this file type"}]
    assert {entry["path"]: entry["reason"] for entry in report["skipped"]}["report.pdf"] == "binary file"


def test_minified_assets_are_skipped_as_generated(run_pristine: RunPristine) -> None:
    minified_bundle = "(function(){" + "var total=price*quantity;" * 60 + "})();\n"
    _, report = run_pristine(
        {
            "static/htmx.min.js": "// readable header\nvar total = price * quantity;\n",
            "static/charts.MIN.mjs": "export const total = 1;\n",
            "static/bundle.js": minified_bundle,
            "static/checkout.js": "var total = price * quantity;\n" * 6 + minified_bundle,
            "static/invoices.py": minified_bundle,
        }
    )
    skipped = {entry["path"]: entry["reason"] for entry in report["skipped"]}
    assert skipped == {
        "static/htmx.min.js": "generated file",
        "static/charts.MIN.mjs": "generated file",
        "static/bundle.js": "generated file",
    }


def test_prose_prone_markers_count_only_in_the_first_five_lines(run_pristine: RunPristine) -> None:
    body = "".join(f"value_{index} = {index}\n" for index in range(8))
    _, report = run_pristine({"pipeline.py": body + "# auto-generated pull requests conflict, so rebase them\n"})
    assert report["skipped"] == []


def test_ruby_files_without_the_rb_suffix_are_checked(run_pristine: RunPristine) -> None:
    ruby = "source 'https://rubygems.org'\n"
    _, report = run_pristine({"Gemfile": ruby, "Podfile": ruby, "app.gemspec": ruby, "config.ru": "run App\n"})
    assert report["unchecked"] == []
    assert report["summary"]["checked_files"] == 4
