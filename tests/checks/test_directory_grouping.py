import pytest

from tests.conftest import RunPristine, rule_findings

RULE_ID = "CR-15"
CODE = "VALUE = 1\n"
WARNING = [(1, "warning")]
DOMAIN_FILES = [
    "invoice.py",
    "invoice_calculation.py",
    "invoice_validation.py",
    "notification.py",
    "notification_preferences.py",
    "notification_rendering.py",
]
UNGROUPED_FILES = ["ledger.py", "pricing.py", "tax.py", "currency.py", "audit.py", "export.py"]


def tree(folder: str, names: list[str]) -> dict[str, str]:
    return {f"{folder}/{name}": CODE for name in names}


def test_crowded_directory_with_several_groups_is_reported(run_pristine: RunPristine) -> None:
    _, report = run_pristine(tree("billing/src", DOMAIN_FILES + UNGROUPED_FILES))
    findings = [finding for finding in report["findings"] if finding["rule_id"] == RULE_ID]
    assert [finding["path"] for finding in findings] == ["billing/src/audit.py"]
    assert "invoice*" in findings[0]["message"]
    assert "notification*" in findings[0]["message"]


@pytest.mark.parametrize(
    "names",
    [
        DOMAIN_FILES + UNGROUPED_FILES[:5],
        DOMAIN_FILES[:3] + UNGROUPED_FILES + ["refund.py", "payout.py", "dispute.py"],
        DOMAIN_FILES + UNGROUPED_FILES + ["refund.py", "payout.py", "dispute.py", "rebate.py"],
        ["get_invoice.py", "get_refund.py", "get_payout.py", "list_invoices.py", "list_refunds.py"]
        + ["list_payouts.py", *UNGROUPED_FILES],
    ],
    ids=["eleven files", "one group", "groups under the share", "verb prefixes"],
)
def test_directory_below_a_threshold_is_not_crowded(run_pristine: RunPristine, names: list[str]) -> None:
    _, report = run_pristine(tree("billing/src", names))
    assert rule_findings(report, RULE_ID) == []


@pytest.mark.parametrize(
    "folder",
    ["billing/tests", "billing/src/services", "billing/migrations", "billing/examples", "billing/generated"],
)
def test_crowded_directory_in_an_exempt_folder_is_not_reported(run_pristine: RunPristine, folder: str) -> None:
    _, report = run_pristine(tree(folder, DOMAIN_FILES + UNGROUPED_FILES))
    assert rule_findings(report, RULE_ID) == []


def test_crowded_directory_ignores_data_and_prose(run_pristine: RunPristine) -> None:
    files = tree("billing/src", DOMAIN_FILES + UNGROUPED_FILES[:5]) | {"billing/src/README.md": "# Billing\n"}
    _, report = run_pristine(files)
    assert rule_findings(report, RULE_ID) == []


def test_crowded_directory_of_go_files_is_a_package(run_pristine: RunPristine) -> None:
    names = [name.replace(".py", ".go") for name in DOMAIN_FILES + UNGROUPED_FILES]
    _, report = run_pristine(tree("billing/ledger", names))
    assert rule_findings(report, RULE_ID) == []


def test_generated_directory_is_not_reported(run_pristine: RunPristine) -> None:
    files = {path: "# Code generated by Speakeasy. DO NOT EDIT.\n" for path in tree("sdk/models", DOMAIN_FILES)}
    _, report = run_pristine(files | tree("sdk/models", UNGROUPED_FILES))
    assert rule_findings(report, RULE_ID) == []


def test_folder_holding_one_file_is_reported(run_pristine: RunPristine) -> None:
    files = tree("billing/src", ["ledger.py", "pricing.py"]) | {"billing/src/refunds/refund_policy.py": CODE}
    _, report = run_pristine(files)
    findings = [finding for finding in report["findings"] if finding["rule_id"] == RULE_ID]
    assert [(finding["path"], finding["line"]) for finding in findings] == [("billing/src/refunds/refund_policy.py", 1)]


