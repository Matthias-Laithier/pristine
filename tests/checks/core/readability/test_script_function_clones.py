from pathlib import Path

import pytest

from pristine.checks.core.readability.function_clones import scripts
from pristine.cli.main import main
from pristine.reports.outcomes import Unchecked
from tests.conftest import RunPristine, parsed_report, rule_findings, run_git

BODY = "const total = order.total; const tax = total * 2; order.total = total; notify(order); save(order); return tax;"
FUNCTION = f"export function settle(order) {{ {BODY} }}\n"
ARROW = f"export const finish = (order) => {{ {BODY} }};\n"


@pytest.mark.parametrize("suffix", ["js", "ts", "tsx", "mjs", "mts"])
def test_script_functions_and_arrows_clone_across_files(run_pristine: RunPristine, suffix: str) -> None:
    _, report = run_pristine({f"invoice.{suffix}": FUNCTION, f"orders.{suffix}": ARROW})
    assert rule_findings(report, "STR-10") == [(1, "warning")]
    finding = next(item for item in report["findings"] if item["check_id"] == "STR-10")
    assert finding["path"] == f"invoice.{suffix}"
    assert f"finish at orders.{suffix}:1" in finding["message"]


@pytest.mark.parametrize(
    "other",
    [
        ARROW.replace("total", "sum"),
        ARROW.replace("* 2", "+ 2"),
        ARROW.replace("notify(order);", ""),
        ARROW.replace("const tax = total * 2;", "const tax = total * 3;"),
    ],
)
def test_script_clones_require_exact_syntax_and_six_statements(run_pristine: RunPristine, other: str) -> None:
    _, report = run_pristine({"invoice.ts": FUNCTION, "orders.ts": other})
    assert rule_findings(report, "STR-10") == []


@pytest.mark.parametrize(
    "path", ["tests/orders.ts", "orders.test.ts", "generated/orders.ts", "vendor/orders.ts", "templates/orders.ts"]
)
def test_script_clone_path_exemptions(run_pristine: RunPristine, path: str) -> None:
    _, report = run_pristine({"invoice.ts": FUNCTION, path: ARROW})
    assert rule_findings(report, "STR-10") == []


def test_generated_script_clone_and_comment_layout(run_pristine: RunPristine) -> None:
    _, report = run_pristine({"invoice.ts": FUNCTION, "orders.ts": "// @generated by protoc\n" + ARROW})
    assert rule_findings(report, "STR-10") == []
    _, report = run_pristine({"orders.ts": ARROW.replace(";", ";\n// note\n")})
    assert rule_findings(report, "STR-10") == [(1, "warning")]


@pytest.mark.parametrize("extra", ["", " save(order);"])
def test_script_statement_threshold_counts_nested_blocks(run_pristine: RunPristine, extra: str) -> None:
    body = "if (order.open) { close(order); notify(order); } else { audit(order); } log(order);" + extra
    _, report = run_pristine({"a.ts": f"function a(order) {{ {body} }}", "b.ts": f"function b(order) {{ {body} }}"})
    assert rule_findings(report, "STR-10") == ([(1, "warning")] if extra else [])


def test_script_clone_compares_repository_when_one_file_is_checked(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    run_git(tmp_path, "init", "--quiet")
    monkeypatch.chdir(tmp_path)
    Path("invoice.ts").write_text(FUNCTION)
    Path("orders.ts").write_text(ARROW)
    main(["check", "orders.ts", "--json"])
    report = parsed_report(capsys.readouterr().out)
    assert rule_findings(report, "STR-10") == [(1, "warning")]
    finding = next(item for item in report["findings"] if item["check_id"] == "STR-10")
    assert finding["path"] == "orders.ts"


def test_script_clone_worker_failure_is_a_verification_gap(
    run_pristine: RunPristine, monkeypatch: pytest.MonkeyPatch
) -> None:
    def failed_workers(paths: list[str], _jobs: int, _command: tuple[str, ...]) -> dict[str, Unchecked]:
        return {path: Unchecked("worker failed") for path in paths}

    monkeypatch.setattr(scripts, "inspect_in_workers", failed_workers)
    _, report = run_pristine({"invoice.ts": FUNCTION})
    finding = next(item for item in report["findings"] if item["check_id"] == "STR-10")
    assert finding["kind"] == "verification"
    assert finding["message"] == "worker failed"
