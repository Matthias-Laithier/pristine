from pathlib import Path
from textwrap import indent

import pytest

from pristine.cli.main import main
from tests.conftest import JsonReport, RunPristine, parsed_report, run_git

CHECK_ID = "STR-10"
SETTLE_BODY = """    total = 0
    for line in order.lines:
        if line.refunded:
            continue
        total += line.amount
    order.total = total
    return total
"""
SHORT_BODY = """    total = sum(line.amount for line in order.lines)
    order.total = total
    return total
"""
RENAMED_BODY = SETTLE_BODY.replace("total", "amount_due")


def module(name: str, body: str, header: str = "") -> str:
    return f'{header}def {name}(order):\n    """Settle the order."""\n{body}'


def method(owner: str, name: str, body: str) -> str:
    return f"class {owner}(Protocol):\n{indent(module(name, body), '    ')}"


def reported_clones(report: JsonReport) -> list[tuple[str, int, str]]:
    return [
        (finding["path"], finding["line"], finding["message"].split(";")[0])
        for finding in report["findings"]
        if finding["check_id"] == CHECK_ID and finding["severity"] == "warning"
    ]


def test_a_clone_group_is_reported_once_on_its_first_path(run_pristine: RunPristine) -> None:
    _, report = run_pristine(
        {
            "billing/invoices.py": module("settle_invoice", SETTLE_BODY),
            "billing/orders.py": f"import json\n\n\n{module('settle_order', SETTLE_BODY)}",
            "shop/checkout.py": method("Checkout", "settle", SETTLE_BODY).replace("(Protocol)", ""),
        }
    )
    assert reported_clones(report) == [
        (
            "billing/invoices.py",
            1,
            (
                "function settle_invoice has the same body as settle_order at billing/orders.py:4, "
                "settle at shop/checkout.py:2"
            ),
        )
    ]


@pytest.mark.parametrize(
    "files",
    [
        {"invoices.py": module("settle_invoice", SHORT_BODY), "orders.py": module("settle_order", SHORT_BODY)},
        {"invoices.py": module("settle_invoice", SETTLE_BODY), "orders.py": module("settle_order", RENAMED_BODY)},
        {"invoices.py": module("settle_invoice", SETTLE_BODY), "tests/test_orders.py": module("settle", SETTLE_BODY)},
        {"invoices.py": module("settle_invoice", SETTLE_BODY), "migrations/0002.py": module("settle", SETTLE_BODY)},
        {"invoices.py": module("settle_invoice", SETTLE_BODY), "template/orders.py": module("settle", SETTLE_BODY)},
        {
            "invoices.py": module("settle_invoice", SETTLE_BODY),
            "orders.py": module("settle", SETTLE_BODY, "# @generated by protoc\n"),
        },
        {
            "invoices.py": module("settle_invoice", SETTLE_BODY, "@overload\n"),
            "orders.py": module("settle_order", SETTLE_BODY, "@typing.overload\n"),
        },
        {
            "invoices.py": method("Settler", "settle", SETTLE_BODY),
            "orders.py": method("Ledger", "settle", SETTLE_BODY),
        },
    ],
    ids=[
        "short",
        "renamed",
        "test file",
        "migration",
        "template",
        "generated",
        "overload",
        "protocol",
    ],
)
def test_short_renamed_and_exempt_bodies_are_not_reported(run_pristine: RunPristine, files: dict[str, str]) -> None:
    _, report = run_pristine(files)
    assert reported_clones(report) == []


@pytest.mark.parametrize(("closing", "expected"), [("", []), ("    order.save()\n", [("invoices.py", 1)])])
def test_statements_count_recursively_from_six_on(
    run_pristine: RunPristine, closing: str, expected: list[tuple[str, int]]
) -> None:
    body = f"    if order.open:\n        order.close()\n        order.notify()\n    else:\n        order.audit()\n    log(order)\n{closing}"
    _, report = run_pristine({"invoices.py": module("close", body), "orders.py": module("finish", body)})
    assert [(path, line) for path, line, _ in reported_clones(report)] == expected


def test_a_checked_file_is_compared_with_the_whole_repository(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    run_git(tmp_path, "init", "--quiet")
    (tmp_path / "app").mkdir()
    monkeypatch.chdir(tmp_path / "app")
    Path("invoices.py").write_text(module("settle_invoice", SETTLE_BODY))
    Path("orders.py").write_text(
        module("settle_order", SETTLE_BODY.replace("    total = 0\n", "    total = 0  # start\n"))
    )
    main(["check", "orders.py", "--json"])
    assert reported_clones(parsed_report(capsys.readouterr().out)) == [
        ("orders.py", 1, "function settle_order has the same body as settle_invoice at invoices.py:1")
    ]
