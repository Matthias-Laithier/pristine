import pytest

from tests.conftest import JsonReport, RunPristine, rule_findings

RULE_ID = "CR-15"
CODE = "VALUE = 1\n"
WARNING = [(1, "warning")]
ERROR = [(1, "error")]
LEDGER_FILES = [f"ledger_{index}.py" for index in range(20)]


def tree(folder: str, names: list[str]) -> dict[str, str]:
    return {f"{folder}/{name}": CODE for name in names}


def severities(report: JsonReport) -> list[tuple[int, str]]:
    return rule_findings(report, RULE_ID)


@pytest.mark.parametrize(("count", "expected"), [(8, []), (9, WARNING), (15, WARNING), (16, ERROR)])
def test_code_files_over_the_limits_are_reported(
    run_pristine: RunPristine, count: int, expected: list[tuple[int, str]]
) -> None:
    _, report = run_pristine(tree("billing/src", LEDGER_FILES[:count]))
    assert severities(report) == expected


def test_crowded_directory_is_reported_on_its_first_file(run_pristine: RunPristine) -> None:
    _, report = run_pristine(tree("billing/src", LEDGER_FILES[:9]))
    findings = [finding for finding in report["findings"] if finding["rule_id"] == RULE_ID]
    assert [finding["path"] for finding in findings] == ["billing/src/ledger_0.py"]
    assert "9 code files" in findings[0]["message"]


def test_count_ignores_subdirectories_data_and_prose(run_pristine: RunPristine) -> None:
    files = tree("billing/src", LEDGER_FILES[:8]) | tree("billing/src/refunds", ["refund.py", "refund_policy.py"])
    _, report = run_pristine(files | {"billing/src/README.md": "# Billing\n", "billing/src/rates.json": "{}\n"})
    assert severities(report) == []


@pytest.mark.parametrize(("marker", "expected"), [("", []), ("\n", []), ("from .ledger_0 import VALUE\n", WARNING)])
def test_only_a_non_empty_package_marker_counts(
    run_pristine: RunPristine, marker: str, expected: list[tuple[int, str]]
) -> None:
    _, report = run_pristine(tree("billing/src", LEDGER_FILES[:8]) | {"billing/src/__init__.py": marker})
    assert severities(report) == expected


def test_declarations_and_stories_do_not_count(run_pristine: RunPristine) -> None:
    names = [f"widget_{index}.tsx" for index in range(8)] + ["widgets.d.ts", "widget_0.stories.tsx"]
    _, report = run_pristine(tree("web/src/widgets", names))
    assert severities(report) == []


@pytest.mark.parametrize(
    "folder",
    ["billing/tests/ledger", "billing/migrations/versions", "billing/node_modules/ledger", "billing/generated"]
    + ["billing/dist", "billing/.github/scripts"],
)
def test_crowded_exempt_folder_is_not_reported(run_pristine: RunPristine, folder: str) -> None:
    _, report = run_pristine(tree(folder, LEDGER_FILES))
    assert severities(report) == []


@pytest.mark.parametrize("folder", ["billing/src/services", "billing/src/templates", "billing/examples"])
def test_crowded_conventional_folder_is_reported(run_pristine: RunPristine, folder: str) -> None:
    _, report = run_pristine(tree(folder, LEDGER_FILES))
