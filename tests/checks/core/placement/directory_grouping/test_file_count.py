@pytest.mark.parametrize("folder", ["web/src/pages", "web/app/routes"])
def test_crowded_routing_directory_is_not_reported(run_pristine: RunPristine, folder: str) -> None:
    _, report = run_pristine(tree(folder, [f"route_{index}.tsx" for index in range(20)]))
    assert severities(report) == []


@pytest.mark.parametrize("folder", ["docs_site/pages", "web/src/pages/chat/components"])
def test_crowded_folder_outside_routes_is_reported(run_pristine: RunPristine, folder: str) -> None:
    names = LEDGER_FILES if folder.startswith("docs") else [f"panel_{index}.tsx" for index in range(20)]
    _, report = run_pristine(tree(folder, names))
    assert severities(report) == ERROR


def test_generated_directory_is_not_reported(run_pristine: RunPristine) -> None:
    files = tree("sdk/models", LEDGER_FILES) | {"sdk/models/model.py": "# Code generated by Speakeasy. DO NOT EDIT.\n"}
    _, report = run_pristine(files)
    assert severities(report) == []
