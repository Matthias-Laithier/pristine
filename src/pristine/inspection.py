import re
from pathlib import Path

from pristine.checks.registry import file_checks
from pristine.outcomes import Checked, Outcome, Skipped, Unchecked
from pristine.parsing import parse_file
from pristine.services.grammars import GrammarError, language_for

BINARY_SNIFF_BYTES = 8192
TEXT_ONLY_BINARY_SIGNATURES = (b"%PDF-",)
GENERATED_MARKER_LINES = 5
GENERATED_MARKERS = ("@generated", "do not edit", "code generated", "auto-generated", "autogenerated")
GENERATOR_FIRST_LINE_MARKERS = ("generated by", "generated with")
MINIFIED_NAME_ENDINGS = (".min.js", ".min.css", ".min.mjs")
MINIFIED_LINE_LENGTH = 1000
SCRIPT_SUFFIXES = frozenset({".js", ".mjs", ".cjs", ".jsx", ".ts", ".mts", ".cts", ".tsx"})
LOCKFILE_NAMES = frozenset(
    {"uv.lock", "poetry.lock", "Pipfile.lock", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock"}
    | {"Cargo.lock", "go.sum", "Gemfile.lock", "composer.lock", "flake.lock", "mix.lock", "pubspec.lock"}
)
PROSE_AND_DATA_SUFFIXES = frozenset(
    {".md", ".mdx", ".rst", ".txt", ".adoc", ".json", ".jsonc", ".json5", ".yaml", ".yml", ".toml", ".ini", ".cfg"}
    | {".conf", ".env", ".csv", ".tsv", ".xml", ".svg", ".html", ".htm", ".css", ".lock", ".properties", ".po"}
    | {".log", ".example", ".typed", ".dat", ".in", ".out", ".golden", ".snap"}
)
IGNORE_LIST_NAME = re.compile(r"\.?[\w-]*ignore")
PROSE_AND_DATA_NAMES = frozenset(
    {".gitattributes", ".gitkeep", ".npmrc", ".nvmrc", ".python-version"}
    | {".editorconfig", "LICENSE", "NOTICE", "README", "CODEOWNERS", "py.typed"}
)


def is_generated(text: str) -> bool:
    header_lines = text.lower().splitlines()[:GENERATED_MARKER_LINES]
    first_line = header_lines[0] if header_lines else ""
    header = "\n".join(header_lines)
    is_marked = any(marker in header for marker in GENERATED_MARKERS)
    return is_marked or any(marker in first_line for marker in GENERATOR_FIRST_LINE_MARKERS)


def is_minified(path: Path, text: str) -> bool:
    if path.name.lower().endswith(MINIFIED_NAME_ENDINGS):
        return True
    header_lines = text.split("\n", GENERATED_MARKER_LINES)[:GENERATED_MARKER_LINES]
    return path.suffix.lower() in SCRIPT_SUFFIXES and any(len(line) > MINIFIED_LINE_LENGTH for line in header_lines)


def skip_reason(path: Path, content: bytes) -> str | None:
    if b"\0" in content[:BINARY_SNIFF_BYTES] or content.startswith(TEXT_ONLY_BINARY_SIGNATURES):
        return "binary file"
    if path.name in LOCKFILE_NAMES:
        return "lockfile"
    is_ignore_list = IGNORE_LIST_NAME.fullmatch(path.name) is not None
    if path.suffix.lower() in PROSE_AND_DATA_SUFFIXES or path.name in PROSE_AND_DATA_NAMES or is_ignore_list:
        return "prose or data file, exempt from these checks"
    return None


def run_checks(shown_path: str, text: str, language: str) -> Outcome:
    try:
        parsed = parse_file(shown_path, text, language)
    except GrammarError as error:
        return Unchecked(f"could not parse as {language}: {error}")
    return Checked([finding for check in file_checks() for finding in check.run(parsed)])


def inspect_file(shown_path: str) -> Outcome:
    path = Path(shown_path)
    try:
        content = path.read_bytes()
    except OSError as error:
        return Unchecked(f"could not read the file: {error.strerror}")
    reason = skip_reason(path, content)
    if reason is not None:
        return Skipped(reason)
    language = language_for(path)
    if language is None:
        return Unchecked("no grammar for this file type")
    text = content.decode(errors="replace")
    if is_generated(text) or is_minified(path, text):
        return Skipped("generated file")
    return run_checks(shown_path, text, language)
